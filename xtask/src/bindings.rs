//! Generates the UI's TypeScript types for the Core API from the Rust definitions.
//!
//! `cargo xtask bindings` writes them; `cargo xtask bindings --check` fails if the committed
//! file is out of date, which CI runs so the two sides can't drift.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use drusite_core::api::{ApiError, Command, Event, Response};
use specta::Types;
use specta_typescript::Typescript;

/// Where the generated types live in the UI.
pub(crate) fn output() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../ui/src/core/types.ts")
}

pub(crate) fn generate() -> Result<String> {
    let types = Types::default()
        .register::<Command>()
        .register::<Response>()
        .register::<Event>()
        .register::<ApiError>();
    Typescript::default()
        .header(
            "// Generated by `cargo xtask bindings` from crates/drusite-core/src/api.rs. Do not edit.\n\
             // SPDX-License-Identifier: AGPL-3.0-or-later",
        )
        .export(&types, specta_serde::Format)
        .context("exporting the TypeScript types")
}

pub(crate) fn run(check: bool) -> Result<bool> {
    let fresh = generate()?;
    let path = output();
    if check {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != fresh {
            eprintln!(
                "{} is out of date: run `cargo xtask bindings`",
                path.display()
            );
            return Ok(false);
        }
        println!("bindings: up to date");
        return Ok(true);
    }
    let Some(dir) = path.parent() else {
        bail!("bad output path")
    };
    std::fs::create_dir_all(dir)?;
    std::fs::write(&path, fresh)?;
    println!("bindings: wrote {}", path.display());
    Ok(true)
}
